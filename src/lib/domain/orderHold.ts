// 「完成」「渡した」の押し間違いを直せる猶予（#45、screens.md §3.5）。
// 押してから、この間は、サーバーに書かない（画面の中だけで、状態を進めて見せる）。「元に戻す」が押されなければ、書く。
// お客様の画面には、間違った状況が、一度も届かない
import type { OrderAction } from './orderStatus';

/**
 * 猶予（ms）。決め方：
 * - 押し間違いに気づく時間：カードが隣の列へ動くので、画面を見ていれば1〜2秒。ボタンへ手を伸ばす時間を足して、3秒は、混雑・手袋・目を離していたときに、足りない
 * - お客様の待ち：「できあがり」の通知が、この分だけ遅れる。受け渡し口へ歩く時間・待ち時間（数分）に比べて、5秒は、わずか。
 *   間違った「できあがり」が届く損（来てしまう・混乱する）は、5秒の遅れより、ずっと大きい。「渡した」の遅れは、お客様に影響しない
 * - 長すぎる害：ほかのスタッフの画面への反映の遅れ、画面を閉じたときに失う危険（閉じる前に、すぐ書くため、小さい）が、時間に比例して増える
 * 実機で、押し間違いに間に合うか・待たされないかを確かめて、必要なら、ここだけを変える
 */
export const UNDO_GRACE_MS = 5000;

/** 猶予の対象（お客様の画面が変わる操作）。「戻す」「取り消し」「取り消しを戻す」は、対象外 */
export function isHoldable(action: OrderAction): boolean {
  return action === 'ready' || action === 'done';
}
